        { title: 'ATM Card Hotlisting Numbers', desc: 'Emergency debit and credit card blocking hotlines', url: 'bank/card', cat: 'bank', icon: 'fas fa-credit-card', badge: 'Hotline' },
        { title: 'Missed Call Balance Numbers', desc: 'Instant account balance checking via missed calls', url: 'bank/account', cat: 'bank', icon: 'fas fa-phone-volume', badge: 'Balance' },
        { title: 'Developer JSON APIs', desc: 'RESTful API documentation and high-speed endpoints', url: 'api', cat: 'legal', icon: 'fas fa-code', badge: 'REST API' }
    ];

    var modal = document.getElementById('cmdPaletteModal');
    var input = document.getElementById('cmdPaletteInput');
    var closeBtn = document.getElementById('cmdPaletteCloseBtn');
    var itemsList = document.getElementById('cmdItemsList');
    var smartMatch = document.getElementById('cmdSmartMatch');
    var smartMatchList = document.getElementById('cmdSmartMatchList');
    var categoryTabs = document.querySelectorAll('#cmdCategoryTabs .cmd-cat-btn');
    var currentFilter = 'all';
    var activeIndex = -1;

    function openCommandPalette() {
        if (!modal) return;
        modal.style.display = 'flex';
        input.value = '';
        currentFilter = 'all';
        categoryTabs.forEach(function(btn) { btn.classList.toggle('active', btn.getAttribute('data-filter') === 'all'); });
        renderToolList();
        setTimeout(function() { input.focus(); }, 50);
        document.body.style.overflow = 'hidden';
    }

    function closeCommandPalette() {
        if (!modal) return;
        modal.style.display = 'none';
        document.body.style.overflow = '';
    }

    function renderToolList() {
        var query = input.value.trim().toLowerCase();
        itemsList.innerHTML = '';
        smartMatch.style.display = 'none';
        smartMatchList.innerHTML = '';
        activeIndex = -1;

        // Smart Pattern Detection for Direct Lookup
        if (query.length > 0) {
            var smartItems = [];
            // 1. PIN code pattern (6 digits)
            if (/^[1-9][0-9]{2,5}$/.test(query)) {
                smartItems.push({
                    title: 'Lookup PIN Code: ' + query.toUpperCase(),
                    desc: 'Direct search postal office and location details',
                    url: 'pincode?pincode=' + encodeURIComponent(query),
                    icon: 'fas fa-map-pin',
                    badge: 'Instant PIN'
                });
            }
            // 2. IFSC code pattern (e.g. SBIN0000691)
            if (/^[a-zA-Z]{2,4}[0-9a-zA-Z]{0,7}$/.test(query) && query.length >= 4) {
                smartItems.push({
                    title: 'Lookup Bank IFSC: ' + query.toUpperCase(),
                    desc: 'Direct query for branch address, RTGS/NEFT & MICR code',
                    url: 'bank-ifsc?ifsc=' + encodeURIComponent(query.toUpperCase()),
                    icon: 'fas fa-university',
                    badge: 'Instant IFSC'
                });
            }
            // 3. Company CIN pattern (21 chars or starts with U/L)
            if (/^[ULul][0-9]{2,5}/.test(query) || query.length >= 8) {
                smartItems.push({
                    title: 'Search MCA Company: ' + query.toUpperCase(),
                    desc: 'Search incorporated entities, LLPs, and CIN records',
                    url: 'company-incorporation?q=' + encodeURIComponent(query),
                    icon: 'fas fa-building',
                    badge: 'Instant CIN'
                });
            }

            if (smartItems.length > 0) {
                smartMatch.style.display = 'block';
                smartItems.forEach(function(item) {
                    var a = document.createElement('a');
                    a.className = 'cmd-item';
                    a.href = baseUrl + item.url;
                    a.innerHTML = 
                        '<div class="cmd-item-icon" style="background: #eff6ff; color: #2563eb;"><i class="' + item.icon + '"></i></div>' +
                        '<div class="cmd-item-content">' +
                            '<div class="cmd-item-title">' + item.title + '</div>' +
                            '<div class="cmd-item-desc">' + item.desc + '</div>' +
                        '</div>' +
                        '<span class="cmd-item-badge" style="background: #eff6ff; color: #2563eb;">' + item.badge + '</span>' +
                        '<i class="fas fa-chevron-right cmd-item-arrow"></i>';
                    smartMatchList.appendChild(a);
                });
            }
        }

        // Filter and display general directories
        var filtered = toolDirectory.filter(function(tool) {
            if (currentFilter !== 'all' && tool.cat !== currentFilter) {
                return false;
            }
            if (query.length > 0) {
                return tool.title.toLowerCase().indexOf(query) !== -1 || 
                       tool.desc.toLowerCase().indexOf(query) !== -1 ||
                       tool.badge.toLowerCase().indexOf(query) !== -1;
            }
            return true;
        });

        if (filtered.length === 0 && smartMatch.style.display === 'none') {
            itemsList.innerHTML = '<div class="text-center py-4 text-muted small"><i class="fas fa-search mb-2" style="font-size: 22px;"></i><br>No matching tools found. Press Enter to search on Homepage.</div>';
            return;
        }

        filtered.forEach(function(tool, idx) {
            var a = document.createElement('a');
            a.className = 'cmd-item';
            a.href = baseUrl + tool.url;
            a.innerHTML = 
                '<div class="cmd-item-icon"><i class="' + tool.icon + '"></i></div>' +
                '<div class="cmd-item-content">' +
                    '<div class="cmd-item-title">' + tool.title + '</div>' +
                    '<div class="cmd-item-desc">' + tool.desc + '</div>' +
                '</div>' +
                '<span class="cmd-item-badge">' + tool.badge + '</span>' +
                '<i class="fas fa-chevron-right cmd-item-arrow"></i>';
            itemsList.appendChild(a);
        });

        // Set default active on first item
        updateActiveHighlight();
    }

    function updateActiveHighlight() {
        var allItems = modal.querySelectorAll('.cmd-item');
        allItems.forEach(function(el, i) {
            el.classList.toggle('active-item', i === activeIndex);
            if (i === activeIndex) {
                el.scrollIntoView({ block: 'nearest' });
            }
        });
    }

    // Event Triggers
    var triggerDesktop = document.getElementById('globalSearchTrigger');
    var triggerMobile = document.getElementById('globalSearchTriggerMobile');
    if (triggerDesktop) triggerDesktop.addEventListener('click', openCommandPalette);
    if (triggerMobile) triggerMobile.addEventListener('click', openCommandPalette);
    if (closeBtn) closeBtn.addEventListener('click', closeCommandPalette);

    if (modal) {
        modal.addEventListener('click', function(e) {
            if (e.target === modal) closeCommandPalette();
        });
    }

    if (input) {
        input.addEventListener('input', renderToolList);
        input.addEventListener('keydown', function(e) {
            var allItems = modal.querySelectorAll('.cmd-item');
            if (e.key === 'ArrowDown') {
                e.preventDefault();
                if (allItems.length > 0) {
                    activeIndex = (activeIndex + 1) % allItems.length;
                    updateActiveHighlight();
                }
            } else if (e.key === 'ArrowUp') {
                e.preventDefault();
                if (allItems.length > 0) {
                    activeIndex = (activeIndex - 1 + allItems.length) % allItems.length;
                    updateActiveHighlight();
                }
            } else if (e.key === 'Enter') {
                e.preventDefault();
                if (activeIndex >= 0 && allItems[activeIndex]) {
                    window.location.href = allItems[activeIndex].getAttribute('href');
                } else if (allItems.length > 0) {
                    window.location.href = allItems[0].getAttribute('href');
                } else if (input.value.trim().length > 0) {
                    window.location.href = baseUrl + 'bank-finder?q=' + encodeURIComponent(input.value.trim());
                }
            } else if (e.key === 'Escape') {
                closeCommandPalette();
            }
        });
    }

    categoryTabs.forEach(function(btn) {
        btn.addEventListener('click', function() {
            categoryTabs.forEach(function(b) { b.classList.remove('active'); });
            this.classList.add('active');
            currentFilter = this.getAttribute('data-filter');
            renderToolList();
            input.focus();
        });
    });

    // Keyboard Shortcuts (Ctrl + K or /)
    document.addEventListener('keydown', function(e) {
        if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'k') {
            e.preventDefault();
            if (modal.style.display === 'flex') {
                closeCommandPalette();
            } else {
                openCommandPalette();
            }
        } else if (e.key === '/' && document.activeElement.tagName !== 'INPUT' && document.activeElement.tagName !== 'TEXTAREA') {
            e.preventDefault();
            openCommandPalette();
        } else if (e.key === 'Escape' && modal && modal.style.display === 'flex') {
            closeCommandPalette();
        }
    });

})();

