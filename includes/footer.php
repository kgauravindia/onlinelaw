$(document).ready(function() {
    // Mobile / Click dropdown support
    $('.navbar-nav .dropdown > a.dropdown-toggle').on('click', function(e) {
        var $parent = $(this).parent('.dropdown');
        var $menu = $parent.find('.dropdown-menu');
        if ($(window).width() < 992) {
            e.preventDefault();
            e.stopPropagation();
            $('.navbar-nav .dropdown').not($parent).removeClass('show').find('.dropdown-menu').removeClass('show');
            $parent.toggleClass('show');
            $menu.toggleClass('show');
        }
    });
    
    // Close dropdown when clicking outside
    $(document).on('click', function(e) {
        if (!$(e.target).closest('.navbar-nav .dropdown').length) {
            $('.navbar-nav .dropdown').removeClass('show').find('.dropdown-menu').removeClass('show');
        }
    });
});
